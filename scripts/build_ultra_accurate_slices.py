def slice_and_encode():
    total_sliced = 0
    for section_key, config in EXAM_TRACKS.items():
        master_file = config["file"]
        out_dir = os.path.join("frontend/public/audio/japanese/slices", section_key)
        os.makedirs(out_dir, exist_ok=True)

        for q_num, start_sec, end_sec in config["slices"]:
            dur_sec = end_sec - start_sec
            out_mp3 = os.path.join(out_dir, f"q{q_num}.mp3")
            
            cmd = [
                ffmpeg_exe, "-y",
                "-ss", str(start_sec),
                "-i", master_file,
                "-t", str(dur_sec),
                "-b:a", "96k",
                out_mp3
            ]
            subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
            total_sliced += 1
            print(f"Generated {out_mp3} ({start_sec}s -> {end_sec}s, dur: {dur_sec}s)", flush=True)

    print(f"\nSuccessfully generated all {total_sliced} ultra-accurate MP3 slices!", flush=True)

if __name__ == "__main__":
    slice_and_encode()
